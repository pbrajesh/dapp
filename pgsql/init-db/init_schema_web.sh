-- // Run against the database 
-- // -d <dbname>

psql -v --username pgdba --dbname dbapp <<EOF

CREATE SCHEMA web
    AUTHORIZATION pgdba;

COMMENT ON SCHEMA web
    IS 'web schema used by REST API';

GRANT ALL ON SCHEMA web TO pgdba WITH GRANT OPTION;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT ALL ON TABLES TO pgdba WITH GRANT OPTION;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT INSERT, SELECT, UPDATE, DELETE ON TABLES TO pgwtr;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT SELECT ON TABLES TO pgrdr WITH GRANT OPTION;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT SELECT, USAGE ON SEQUENCES TO pgdba WITH GRANT OPTION;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT SELECT, USAGE ON SEQUENCES TO pgrdr;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT SELECT, USAGE ON SEQUENCES TO pgwtr;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT EXECUTE ON FUNCTIONS TO pgdba WITH GRANT OPTION;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT EXECUTE ON FUNCTIONS TO pgrdr;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT EXECUTE ON FUNCTIONS TO pgwtr;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT USAGE ON TYPES TO pgdba WITH GRANT OPTION;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT USAGE ON TYPES TO pgrdr;

ALTER DEFAULT PRIVILEGES IN SCHEMA web
GRANT USAGE ON TYPES TO pgwtr;

ALTER ROLE pgdba SET search_path TO public, web;
ALTER ROLE pgwtr SET search_path TO public, web;
ALTER ROLE pgrdr SET search_path TO public, web;

EOF